  def system_prompt(variant)
    <<~PROMPT
      Ты помощник техподдержки. Ты получаешь сырое обращение: оно может быть переслано сотрудником, содержать цитаты, эмоции и опечатки. Приведи его к единой форме.

      КТО ЕСТЬ КТО
      - Сотрудники поддержки, они НИКОГДА не авторы обращения: #{SUPPORT_STAFF.join(", ")}.
      - Автор обращения — человек, у которого проблема. Если обращение переслано сотрудником, автор — тот, чьи слова процитированы или о ком идёт речь.

      ПРАВИЛА
      1. Сохрани все факты, просьбы, сроки, названия, логины и номера. Не добавляй ничего, чего нет в тексте.
      2. Убери приветствия, эмоции, оценки и обращения к сотрудникам ("Михаил М. может...", "Здравствуйте, Александр").
      3. Пиши от третьего лица: кто и что просит. Не пиши, кто из сотрудников должен это сделать.
      4. Имена людей записывай как "Имя Ф." (Юлия Иванова -> Юлия И.).
      5. type — ровно одно значение из списка: #{TICKET_TYPES.join(", ")}. Если ничего не подходит — "другое".
      6. issuer — "Имя Ф., логин" автора. Если имени или логина нет в тексте, пропусти эту часть, не придумывай.
      7. #{BODY_RULES.fetch(variant).strip}
      8. extra — до 2 коротких предложений: переслано ли обращение, чего не хватает, что неясно. Не пересказывай body.

      ФОРМАТ
      Отвечай только JSON, без текста до и после.
    PROMPT
  end

  def self.call(ticket)
    raise "No ticket" unless ticket
    new.call(ticket)
  end

  def call(ticket)
    p "---___--____---___---___---"
    system_prompt = system_prompt(:short)
    p system_prompt
    ticket_prompt = "Обращение для преобразования: #{ticket.message_payload} #{ticket.image_payload}"
    p "---___---____--___"
    p ticket_prompt
    ollama_api = OllamaApi.new
    response = ollama_api.transform_ticket(system_prompt, ticket_prompt)
    p "---___---___--"
    body = response.body

    api    = JSON.parse(response.body)   # ответ Ollama целиком
    ticket_info = JSON.parse(api["response"])

    body = ticket_info["body"]   # => "Автор обращения просит перевести Веснин Георгий..."
    type = ticket_info["type"]
    issuer = ticket_info["issuer"]
    extra = ticket_info["extra"]

    p body
    ticket.body = body
    ticket.save!
  end
