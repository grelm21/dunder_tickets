  TICKET_TYPES = [ "удаление из проекта", "доступ", "ошибка", "консультация", "другое" ].freeze

  SUPPORT_STAFF = [
    "Михаил", "Михаил М.", "Mihail M", "Mihail Munaev", "MihailMNV",
