  BODY_RULES = {
    short: <<~TXT,
      body: 1-4 предложения связным текстом, все факты и просьбы, срок если есть.
    TXT
    structured: <<~TXT,
      body: строки, разделённые \\n, строго в таком порядке:
      "Суть: ...", "Подробности: ...", "Что нужно: ...", "Срок: ..." (строку "Срок" пропусти, если срока нет).
    TXT
    split: <<~TXT
      body: контекст проблемы, 1-3 предложения, без перечисления просьб.
      requests: массив строк, по одной на каждое отдельное действие, срок указывай внутри строки.
    TXT
  }.freeze

